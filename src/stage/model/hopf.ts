// The Hopf fibration S^1 → S^3 → S^2, in the conventions used throughout the
// Hopf article. One set of conventions, stated once:
//
//   S^3 ⊂ R^4 = C^2:   q = (x0, x1, x2, x3) ↔ (z1, z2) = (x0 + i x1, x2 + i x3),
//                       which as a quaternion is q = z1 + z2 j  (so (1, i, j, k) = (e1, e2, e3, e4)).
//   Hopf map:           h(z1, z2) = (2 Re(z1 z̄2), 2 Im(z1 z̄2), |z1|² − |z2|²) ∈ S^2 ⊂ R^3.
//                       In quaternion language h(q) is the pure quaternion q̄ i q, read in the axes (k, j, i)
//                       (checked numerically). With z1 = r1 e^{iα}, z2 = r2 e^{iβ}: latitude cos ϑ = r1² − r2²,
//                       longitude λ = α − β. The map keeps the balance and the angle difference of the two
//                       "dials" z1, z2 and forgets their common turn.
//   Fibre:              (z1, z2) ↦ (e^{iθ} z1, e^{iθ} z2) = left multiplication by e^{iθ} = cos θ + i sin θ,
//                       i.e. the left-isoclinic rotation generated by i_L. The fibre over p is a great circle.
//   Stereographic map:  from the pole N = (0, 0, 0, 1):  σ(x) = (x0, x1, x2) / (1 − x3).
//                       The fibre over the south pole (0, 0, −1) of S^2 passes through N and becomes the z-axis;
//                       the fibre over the north pole (0, 0, 1) is the unit circle in the xy-plane.
//   Connection:         the vertical direction at q is i·q (the fibre tangent); horizontal = its orthogonal
//                       complement in T_q S^3 for the round metric. Connection form A_q(v) = ⟨i q, v⟩.
//                       Holonomy of a loop on S^2: the horizontal lift ends at e^{iγ}·start with
//                       γ = +½ Ω (mod 2π), Ω the solid angle enclosed on the LEFT of the loop (checked
//                       numerically: the 60° latitude, run counterclockwise seen from above the north pole,
//                       gives γ = π/2; the equator gives γ = π, i.e. the lift ends at −start).
//                       Curvature: dA = ½ · (area form of S^2); its integral is 2π (Chern number 1).
//   Tori:               the fibres over the latitude ϑ fill the torus of revolution about the z-axis with
//                       core radius sec(ϑ/2) and tube radius tan(ϑ/2) (so R² − r² = 1); every fibre on it is
//                       a Villarceau circle. Any two fibres are linked once (Gauss integral = +1).

import type { Vec3 } from './vec3';
import type { Quat } from './quaternion';
import { cross, dot, normalize, sub, scale, add, length } from './vec3';

export type S3Point = Quat; // [x0, x1, x2, x3], |·| = 1

/** Left multiplication by e^{iθ}: moves a point of S^3 along its own fibre. */
export function alongFibre(q: S3Point, theta: number): S3Point {
  const c = Math.cos(theta);
  const s = Math.sin(theta);
  return [c * q[0] - s * q[1], s * q[0] + c * q[1], c * q[2] - s * q[3], s * q[2] + c * q[3]];
}

/** The fibre tangent i·q at q (unit length when |q| = 1). */
export const fibreTangent = (q: S3Point): S3Point => [-q[1], q[0], -q[3], q[2]];

/** The Hopf map h: S^3 → S^2. */
export function hopf(q: S3Point): Vec3 {
  const [a, b, c, d] = q; // z1 = a + i b, z2 = c + i d; z1 z̄2 = (ac + bd) + i (bc − ad)
  return [2 * (a * c + b * d), 2 * (b * c - a * d), a * a + b * b - c * c - d * d];
}

/**
 * A point of the fibre over p ∈ S^2, at fibre angle θ. θ = 0 gives a continuous
 * section away from the south pole: z1 = √((1 + pz) / 2) real, z2 = (px − i py) / (2 z1).
 */
export function fibrePoint(p: Vec3, theta = 0): S3Point {
  const [px, py, pz] = p;
  if (pz < -1 + 1e-9) return alongFibre([0, 0, 1, 0], theta); // the fibre over the south pole: z1 = 0, |z2| = 1
  const z1 = Math.sqrt((1 + pz) / 2);
  const base: S3Point = [z1, 0, px / (2 * z1), -py / (2 * z1)];
  return alongFibre(base, theta);
}

/** Stereographic projection from N = (0, 0, 0, 1). Returns null at the pole. */
export function stereographic(q: S3Point): Vec3 | null {
  const w = 1 - q[3];
  if (w < 1e-9) return null;
  return [q[0] / w, q[1] / w, q[2] / w];
}

/** Inverse stereographic projection: a point of R^3 back onto S^3. */
export function unstereographic(x: Vec3): S3Point {
  const r2 = x[0] * x[0] + x[1] * x[1] + x[2] * x[2];
  const d = 1 + r2;
  return [(2 * x[0]) / d, (2 * x[1]) / d, (2 * x[2]) / d, (r2 - 1) / d];
}

export interface Circle3 {
  center: Vec3;
  radius: number;
  /** Unit normal of the plane of the circle. */
  normal: Vec3;
  /** Orthonormal basis of that plane, so that points are center + r (cos s · u + sin s · v). */
  u: Vec3;
  v: Vec3;
}

/** The circle through three points of R^3 (its circumcircle), or null if they are collinear. */
export function circleThrough(a: Vec3, b: Vec3, c: Vec3): Circle3 | null {
  const ab = sub(b, a);
  const ac = sub(c, a);
  const n = cross(ab, ac);
  const nn = dot(n, n);
  if (nn < 1e-18) return null;
  const t = scale(sub(scale(cross(n, ab), dot(ac, ac)), scale(cross(n, ac), dot(ab, ab))), 1 / (2 * nn));
  const center = add(a, t);
  const radius = length(t);
  const normal = normalize(n);
  const u = normalize(sub(a, center));
  const v = cross(normal, u);
  return { center, radius, normal, u, v };
}

/**
 * The stereographic image of the fibre over p: a circle in R^3, or null for the
 * fibre over the south pole, which becomes the z-axis.
 */
export function fibreCircle(p: Vec3): Circle3 | null {
  if (p[2] < -1 + 1e-6) return null;
  const pts = [0, 2.1, 4.2].map((theta) => stereographic(fibrePoint(p, theta)));
  if (pts.some((x) => x === null)) return null;
  return circleThrough(pts[0] as Vec3, pts[1] as Vec3, pts[2] as Vec3);
}

/**
 * Sample the stereographic image of the fibre over p: n points, in fibre order.
 * Near the pole the image runs off to infinity; points farther than `limit` from
 * the origin are returned as null so callers can lift the pen.
 */
export function fibreSamples(p: Vec3, n = 120, theta0 = 0, limit = 60): (Vec3 | null)[] {
  const out: (Vec3 | null)[] = [];
  for (let i = 0; i <= n; i++) {
    const q = fibrePoint(p, theta0 + (2 * Math.PI * i) / n);
    const x = stereographic(q);
    out.push(x && length(x) < limit ? x : null);
  }
  return out;
}

/** Points of S^2 as (latitude φ from the north pole, longitude λ). */
export const spherePoint = (polar: number, azimuth: number): Vec3 => [Math.sin(polar) * Math.cos(azimuth), Math.sin(polar) * Math.sin(azimuth), Math.cos(polar)];

/** Solid angle enclosed by a closed polygon on the unit sphere (Van Oosterom–Strackee), to the left of its direction. */
export function solidAngle(loop: Vec3[]): number {
  // sum of the signed solid angles of the triangles (c, loop[i], loop[i+1]) with c = a point inside; use the loop's mean direction
  const mean = normalize(loop.reduce((acc, p) => add(acc, p), [0, 0, 0] as Vec3));
  let total = 0;
  for (let i = 0; i < loop.length; i++) {
    const a = mean;
    const b = loop[i];
    const c = loop[(i + 1) % loop.length];
    const num = dot(a, cross(b, c));
    const den = 1 + dot(a, b) + dot(b, c) + dot(c, a);
    total += 2 * Math.atan2(num, den);
  }
  return total;
}

/**
 * Horizontal lift of a closed loop on S^2 (points γ_0 … γ_n, with γ_n = γ_0 for a closed loop),
 * starting at fibre angle theta0 over γ_0. Returns the lifted points q_k ∈ S^3 and the fibre
 * angle θ_k of each relative to the section fibrePoint(γ_k, 0); the holonomy is θ_n − θ_0.
 *
 * Writing q = e^{iθ} q₀(s) with q₀ the section, horizontality ⟨i q, q'⟩ = 0 gives θ' = −⟨i q₀, q₀'⟩,
 * integrated here with the midpoint rule along the polygon.
 */
export function horizontalLift(loop: Vec3[], theta0 = 0): { points: S3Point[]; angles: number[] } {
  const section = loop.map((p) => fibrePoint(p, 0));
  const angles = [theta0];
  const points = [alongFibre(section[0], theta0)];
  let theta = theta0;
  for (let k = 1; k < loop.length; k++) {
    const a = section[k - 1];
    const b = section[k];
    const mid: Quat = [a[0] + b[0], a[1] + b[1], a[2] + b[2], a[3] + b[3]];
    const n = Math.hypot(mid[0], mid[1], mid[2], mid[3]);
    const m: Quat = [mid[0] / n, mid[1] / n, mid[2] / n, mid[3] / n];
    const dq: Quat = [b[0] - a[0], b[1] - a[1], b[2] - a[2], b[3] - a[3]];
    const iq = fibreTangent(m);
    theta -= iq[0] * dq[0] + iq[1] * dq[1] + iq[2] * dq[2] + iq[3] * dq[3];
    angles.push(theta);
    points.push(alongFibre(b, theta));
  }
  return { points, angles };
}

/** A latitude circle of S^2 at polar angle `polar` (from the north pole), n points, closed. */
export const latitudeLoop = (polar: number, n = 240, azimuth0 = 0): Vec3[] =>
  Array.from({ length: n + 1 }, (_, i) => spherePoint(polar, azimuth0 + (2 * Math.PI * i) / n));

/** The Clifford torus of fibres over the latitude circle at polar angle `polar`, as a parametric surface (θ along the fibre, λ around). */
export const hopfTorusPoint = (polar: number) => (theta: number, lambda: number): Vec3 => stereographic(fibrePoint(spherePoint(polar, lambda), theta)) ?? [0, 0, 1e6];

/** Great-circle arc from a to b on S^2 (unit vectors), n + 1 points including both ends. */
export function geodesicArc(a: Vec3, b: Vec3, n = 60): Vec3[] {
  const d = Math.max(-1, Math.min(1, dot(a, b)));
  const omega = Math.acos(d);
  const out: Vec3[] = [];
  for (let i = 0; i <= n; i++) {
    const u = i / n;
    if (omega < 1e-9) {
      out.push(a);
      continue;
    }
    const s0 = Math.sin((1 - u) * omega) / Math.sin(omega);
    const s1 = Math.sin(u * omega) / Math.sin(omega);
    out.push([a[0] * s0 + b[0] * s1, a[1] * s0 + b[1] * s1, a[2] * s0 + b[2] * s1]);
  }
  return out;
}

/** A closed geodesic polygon through the given vertices (closed: the last point equals the first). */
export function geodesicPolygon(vertices: Vec3[], perEdge = 60): Vec3[] {
  const out: Vec3[] = [];
  vertices.forEach((v, i) => {
    const arc = geodesicArc(v, vertices[(i + 1) % vertices.length], perEdge);
    out.push(...arc.slice(0, -1));
  });
  out.push(vertices[0]);
  return out;
}

/**
 * Holonomy angle γ ∈ (−π, π] of a closed loop on S^2 (first point = last point): the lift ends at
 * e^{iγ}·start. Also returns the lifted points, for drawing.
 */
export function holonomy(loop: Vec3[], theta0 = 0): { gamma: number; points: S3Point[]; angles: number[] } {
  const { points, angles } = horizontalLift(loop, theta0);
  const raw = angles[angles.length - 1] - angles[0];
  const gamma = Math.atan2(Math.sin(raw), Math.cos(raw));
  return { gamma, points, angles };
}

/** Wrap an angle to (−π, π]. */
export const wrapAngle = (a: number) => Math.atan2(Math.sin(a), Math.cos(a));

/** Gauss linking integral of two closed polylines in R^3 (n segments each). */
export function linkingNumber(a: Vec3[], b: Vec3[]): number {
  let s = 0;
  for (let i = 0; i < a.length - 1; i++) {
    const da = sub(a[i + 1], a[i]);
    const ma = scale(add(a[i], a[i + 1]), 0.5);
    for (let j = 0; j < b.length - 1; j++) {
      const db = sub(b[j + 1], b[j]);
      const r = sub(ma, scale(add(b[j], b[j + 1]), 0.5));
      const rn = length(r);
      s += dot(r, cross(da, db)) / (rn * rn * rn);
    }
  }
  return s / (4 * Math.PI);
}

/** The longitude λ ∈ (−π, π] and polar angle ϑ ∈ [0, π] of a point of S^2. */
export const sphericalCoordinates = (p: Vec3) => ({ polar: Math.acos(Math.max(-1, Math.min(1, p[2]))), azimuth: Math.atan2(p[1], p[0]) });
